#!/usr/bin/env python3
"""LeetCode リポジトリの README.md を、フォルダ構成から自動生成する。

想定する構成（LeetHub 3.0 の「言語/難易度」整理）:
    <Language>/<Easy|Medium|Hard>/<NNNN-slug>/{<solution>, README.md}

LeetHub が管理する <!---LeetCode Topics Start--> 〜 End の部分はそのまま残し、
<details> で折りたたむ。それ以外はすべてこのスクリプトが毎回作り直す。
標準ライブラリのみ使用。
"""
from __future__ import annotations

import re
import sys
from pathlib import Path
from urllib.parse import quote

# ===== 設定 =====
REPO_URL = "https://github.com/w4ter-fox/LeetCode"
BRANCH = "main"
LEETCODE_USERNAME = ""  # 例: "w4ter-fox"。空ならプロフィールバッジを出さない
TITLE = "LeetCode solutions"
TAGLINE = "Daily practice toward SWE interviews — auto-synced with LeetHub"
# ================

ROOT = Path(__file__).resolve().parent.parent
DIFFICULTIES = ["Easy", "Medium", "Hard"]
DIFF_COLOR = {"Easy": "3B6D11", "Medium": "BA7517", "Hard": "A32D2D"}
TOPICS_START = "<!---LeetCode Topics Start-->"
TOPICS_END = "<!---LeetCode Topics End-->"
SKIP_DIRS = {".git", ".github", "scripts"}
SLUG_RE = re.compile(r"^\d{4}-")
H2_RE = re.compile(r'<h2><a href="([^"]+)">(.*?)</a></h2>', re.S)


def badge(label: str, message: str, color: str, style: str = "flat-square") -> str:
    def esc(s: str) -> str:
        return quote(s.replace("-", "--").replace("_", "__"), safe="")
    return f"https://img.shields.io/badge/{esc(label)}-{esc(message)}-{color}?style={style}"


def collect() -> dict[str, dict]:
    """slug -> {difficulty, title, url, langs: {lang: path}}"""
    problems: dict[str, dict] = {}
    for lang_dir in sorted(p for p in ROOT.iterdir() if p.is_dir() and p.name not in SKIP_DIRS):
        for diff in DIFFICULTIES:
            diff_dir = lang_dir / diff
            if not diff_dir.is_dir():
                continue
            for prob in sorted(p for p in diff_dir.iterdir() if p.is_dir() and SLUG_RE.match(p.name)):
                slug = prob.name
                entry = problems.setdefault(slug, {
                    "difficulty": diff,
                    "title": slug,
                    "url": f"https://leetcode.com/problems/{slug[5:]}/",
                    "langs": {},
                })
                readme = prob / "README.md"
                if readme.is_file():
                    m = H2_RE.search(readme.read_text(encoding="utf-8", errors="ignore"))
                    if m:
                        entry["url"] = m.group(1)
                        title = re.sub(r"<[^>]+>", "", m.group(2)).strip()
                        entry["title"] = re.sub(r"^\d+\.\s*", "", title)  # "1. Two Sum" -> "Two Sum"
                entry["langs"][lang_dir.name] = prob.relative_to(ROOT).as_posix()
    return problems


def render(problems: dict[str, dict], topics_block: str | None) -> str:
    by_diff = {d: [] for d in DIFFICULTIES}
    lang_count: dict[str, int] = {}
    for slug, p in sorted(problems.items()):
        by_diff[p["difficulty"]].append((slug, p))
        for lang in p["langs"]:
            lang_count[lang] = lang_count.get(lang, 0) + 1

    out: list[str] = []
    out.append('<div align="center">\n')
    out.append(f"# {TITLE}\n")
    out.append(f"{TAGLINE}\n")
    badges = [f'<img src="{badge("solved", str(len(problems)), "185FA5")}" alt="solved">']
    for lang, n in sorted(lang_count.items(), key=lambda x: (-x[1], x[0])):
        badges.append(f'<img src="{badge(lang, str(n), "3B6D11")}" alt="{lang}">')
    if LEETCODE_USERNAME:
        badges.append(
            f'<a href="https://leetcode.com/u/{LEETCODE_USERNAME}/">'
            f'<img src="{badge("LeetCode", "profile", "854F0B")}" alt="LeetCode profile"></a>'
        )
    out.append("\n".join(badges) + "\n")
    out.append("</div>\n")

    out.append("## Progress\n")
    out.append('<p align="center">')
    out.append("\n".join(
        f'<img src="{badge(d, str(len(by_diff[d])), DIFF_COLOR[d], "for-the-badge")}" alt="{d}">'
        for d in DIFFICULTIES
    ))
    out.append("</p>\n")

    out.append("## Problems by difficulty\n")
    for d in DIFFICULTIES:
        rows = by_diff[d]
        out.append(f"<details>\n<summary><b>{d}</b> ({len(rows)})</summary>\n")
        if rows:
            out.append("| # | Problem | Solution |")
            out.append("| --- | --- | --- |")
            for slug, p in rows:
                sols = " · ".join(
                    f"[{lang}]({REPO_URL}/tree/{BRANCH}/{quote(path)}/)"
                    for lang, path in sorted(p["langs"].items())
                )
                title = p["title"].replace("|", "\\|")
                out.append(f"| {slug[:4]} | [{title}]({p['url']}) | {sols} |")
        else:
            out.append("_No problems yet._")
        out.append("\n</details>\n")

    if topics_block:
        out.append("## By topic\n")
        out.append("<details>\n<summary>Show all topics — auto-generated by LeetHub</summary>\n")
        out.append(topics_block)
        out.append("\n</details>")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    readme = ROOT / "README.md"
    current = readme.read_text(encoding="utf-8") if readme.exists() else ""
    topics_block = None
    s, e = current.find(TOPICS_START), current.find(TOPICS_END)
    if s != -1 and e != -1 and s < e:
        topics_block = current[s:e + len(TOPICS_END)]
    new = render(collect(), topics_block)
    if new == current:
        print("README.md: no change")
        return 0
    readme.write_text(new, encoding="utf-8")
    print("README.md: updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
